import { build } from 'esbuild'
import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const directory = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(directory, '../../..')
const licenses = await Promise.all(
  ['image-q', 'culori'].map(
    async (name) =>
      `${name}\n${await readFile(path.join(root, 'node_modules', name, 'LICENSE'), 'utf8')}`,
  ),
)
const result = await build({
  entryPoints: [path.join(directory, 'main.js')],
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: 'chrome120',
  minify: true,
  write: false,
  legalComments: 'inline',
  alias: { '@renderer': path.join(root, 'src/renderer') },
  loader: { '.jpg': 'dataurl', '.webp': 'dataurl' },
})
await writeFile(
  path.join(directory, 'runtime.js'),
  `/* Generated by build.mjs.\n${licenses.join('\n\n').replaceAll('*/', '* /')}\n*/\n${result.outputFiles[0].text}`,
  'utf8',
)
