const { app, BrowserWindow } = require('electron')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
app.setPath('userData', fs.mkdtempSync(path.join(os.tmpdir(), 'auralis-palette-study-')))
app.whenReady().then(async () => {
  const win = new BrowserWindow({show:false,width:1440,height:1000,webPreferences:{sandbox:true,contextIsolation:true,nodeIntegration:false}})
  await win.loadFile(path.join(__dirname,'index.html'))
  await new Promise(resolve => setTimeout(resolve, 2500))
  let state = await win.webContents.executeJavaScript(`({status:document.querySelector('#status').textContent, count:document.querySelectorAll('.card').length, colors:[...document.querySelectorAll('.source code')].map(x=>x.textContent)})`)
  if (state.count !== 4 || state.colors.length !== 4) throw new Error(JSON.stringify(state))
  await win.webContents.executeJavaScript(`(async()=>{const c=document.createElement('canvas');c.width=c.height=48;const x=c.getContext('2d');x.fillStyle='#808080';x.fillRect(0,0,48,48);const b=await new Promise(r=>c.toBlob(r));const input=document.querySelector('#upload');const dt=new DataTransfer();dt.items.add(new File([b],'gray.png',{type:'image/png'}));input.files=dt.files;input.dispatchEvent(new Event('change',{bubbles:true}))})()`)
  await new Promise(resolve => setTimeout(resolve, 2500))
  state = await win.webContents.executeJavaScript(`({status:document.querySelector('#status').textContent, count:document.querySelectorAll('.card').length, colors:[...document.querySelectorAll('.source code')].map(x=>x.textContent), notes:[...document.querySelectorAll('.method')].map(x=>x.textContent)})`)
  if (state.count !== 4 || !state.status.includes('四种方案')) throw new Error(JSON.stringify(state))
  console.log('Gray upload:', JSON.stringify(state))
  await win.setContentSize(540,900)
  const layout = await win.webContents.executeJavaScript(`({width:document.documentElement.clientWidth, scroll:document.documentElement.scrollWidth, cards:document.querySelectorAll('.card').length})`)
  if (layout.scroll > layout.width) throw new Error(JSON.stringify(layout))
  console.log('Narrow layout:', JSON.stringify(layout))
  app.quit()
}).catch(e=>{console.error(e);app.exit(1)})
